export const LANGS = [
  { code: 'en', label: 'EN' },
  { code: 'th', label: 'TH' },
  { code: 'ja', label: 'JP' },
];

const dict = { en, th, ja };
let lang = localStorage.getItem('kuess:lang') || 'en';
if (!dict[lang]) lang = 'en';

export const getLang = () => lang;

export function setLang(code) {
  if (!dict[code]) return;
  lang = code;
  localStorage.setItem('kuess:lang', code);
  document.documentElement.lang = code;
}

// t('left', { n: 2 }) picks left_one / left_other, then fills {n}.
export function t(key, vars = {}) {
  const d = dict[lang];
  let s = d[key];
  if (s === undefined && 'n' in vars) s = (vars.n === 1 && d[key + '_one']) || d[key + '_other'];
  if (s === undefined) s = en[key] ?? (vars.n === 1 ? en[key + '_one'] : en[key + '_other']) ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : ''));
}

document.documentElement.lang = lang;
